def get_schema_for_table(table_name: str) -> StructType:
    """Returns the explicit StructType for a given table name."""
    base_name = table_name.split("/")[-1].split("\\")[-1]
    if base_name in TABLE_SCHEMAS:
        return TABLE_SCHEMAS[base_name]
    raise ValueError(f"No predefined schema contract found for: {table_name}")
